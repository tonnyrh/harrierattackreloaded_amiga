from pathlib import Path
from PIL import Image
import sys
r=Path(__file__).resolve().parents[1]
sys.path.insert(0,str(r/'tools'))
from amiga_graphics_format import project_palette_rgb
pal=project_palette_rgb()
# Source already has alpha. Do NOT infer transparency from dark corner RGB:
# the rig's black girders touch the border and must remain opaque.
im=Image.open(r/'amiga/assets/oil-platform/source-v2.png').convert('RGBA').resize((96,64),Image.Resampling.BOX)
master=Image.new('P',im.size,0)
master.putpalette([v for c in pal for v in c]+[0]*(768-len(pal)*3))
for y in range(64):
 for x in range(96):
  c=im.getpixel((x,y))
  if c[3]>=128:
   pen=min((2,3,4,6,10,12),key=lambda p:sum((pal[p][j]-c[j])**2 for j in range(3)))
   master.putpixel((x,y),pen)
master.save(r/'amiga/assets/oil-platform/platform.png',transparency=0)
im=Image.open(r/'amiga/assets/oil-platform/platform.png').convert('RGBA')
data=[]
for ty in range(8):
 for tx in range(12):
  for y in range(8):
   planes=[0]*5
   for x in range(8):
    rgba=im.getpixel((tx*8+x,ty*8+y))
    if rgba[3]<128: continue
    pen=min((2,3,4,6,10,12),key=lambda p:sum((pal[p][c]-rgba[c])**2 for c in range(3)))
    for p in range(4):
     if pen&(1<<p): planes[p]|=128>>x
    planes[4]|=128>>x
   data.extend(planes)
(r/'amiga/assets/oil-platform/platform_tiles.h').write_text('/* Generated by tools/pack-oil-platform.py. 96x64 masked tiles. */\nstatic const UBYTE oilPlatformTiles[3840] = {\n'+',\n'.join(','.join(str(x) for x in data[i:i+40]) for i in range(0,len(data),40))+'\n};\n')
print('Packed',len(data),'bytes; zero new Chip RAM')
